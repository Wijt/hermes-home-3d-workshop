"""gcode.py: header parsing, first-layer footprint, eject marker, eject eligibility (synthetic G-code only)."""

from __future__ import annotations

import pytest

from home3d_ws.home3d import gcode
from home3d_ws.home3d.gcode import GcodeInfo, assess_eject, footprint_at, inspect_gcode


def make_gcode(w=40.0, d=30.0, h=10.0, *, material="PLA", nozzle=220, bed=65, model="Bambu Lab A1",
               eject=False, prime_tower=False, brim=0.0, skirt=False, layer_h=0.2, cx=128.0, cy=128.0,
               top_scale=1.0, objects=1, arcs="", header=True, marker="; Z_HEIGHT: {z}",
               body_marker="HOME3D AUTO-EJECT", extra_config=()) -> str:
    """Bambu/Orca-style G-code: a rectangular part (optionally tapering to ``top_scale`` at the top)."""
    zs = [round(layer_h * (i + 1), 3) for i in range(max(1, round(h / layer_h)))]
    out = []
    a = out.append
    if header:
        a("; HEADER_BLOCK_START")
        a("; generated by test (OrcaSlicer-style)")
        a("; model printing time: 1h 2m 3s; total estimated time: 1h 10m 3s")
        a(f"; total layer number: {len(zs) * objects}")
        a("; total filament weight [g] : 12.34")
        a(f"; max_z_height: {zs[-1]:.2f}")
        a("; filament: 1")
        a("; HEADER_BLOCK_END")
    a("; CONFIG_BLOCK_START")
    a("; curr_bed_type = Textured PEI Plate")
    a(f"; enable_prime_tower = {1 if prime_tower else 0}")
    a(f"; filament_type = {material}")
    a(f"; textured_plate_temp = {bed}")
    a(f"; nozzle_temperature = {nozzle}")
    a(f"; printer_model = {model}")
    if eject:
        a("; machine_end_gcode = M400\\n;===== " + body_marker + " v1 =====\\nG1 Z2.5\\n")
    for line in extra_config:
        a(line)
    a("; CONFIG_BLOCK_END")
    a("; EXECUTABLE_BLOCK_START")
    a(f"M140 S{bed}")
    a(f"M190 S{bed}")
    a(f"M104 S{nozzle}")
    a("G90")
    a("M83")
    # start-gcode purge line on the plate's front edge (before the first layer marker: must be ignored)
    a("G1 X108 Y-0.5 Z0.3 F3000")
    a("G1 X168 E5 F1200")
    for obj in range(objects):
        ox = cx + obj * (w + 20)
        for i, z in enumerate(zs):
            scale = 1.0 + (top_scale - 1.0) * (i / max(1, len(zs) - 1))
            hw, hd = w * scale / 2, d * scale / 2
            a(marker.format(z=z))
            a(f"; LAYER_HEIGHT: {layer_h}")
            a(f"G1 Z{z} F720")
            if i == 0 and skirt:
                a("; FEATURE: Skirt")
                a(f"G1 X{ox - hw - 30} Y{cy - hd - 30} F42000")
                a(f"G1 X{ox + hw + 30} Y{cy - hd - 30} E2")
            if i == 0 and brim:
                a("; FEATURE: Brim")
                a(f"G1 X{ox - hw - brim} Y{cy - hd - brim} F42000")
                a(f"G1 X{ox + hw + brim} Y{cy - hd - brim} E1")
                a(f"G1 X{ox + hw + brim} Y{cy + hd + brim} E1")
            if i == 0 and prime_tower:
                a("; FEATURE: Prime tower")
                a("G1 X15 Y220 F42000")
                a("G1 X50 Y240 E1")
            a("; FEATURE: Outer wall")
            a(f"G1 X{ox - hw:.3f} Y{cy - hd:.3f} F42000")
            if arcs:
                # half circle from the left-bottom to the right-bottom corner: G3 (CCW) dips below the
                # part, G2 (CW) bulges up into it
                a(f"{arcs} X{ox + hw:.3f} Y{cy - hd:.3f} I{hw:.3f} J0 E1.5")
            else:
                a(f"G1 X{ox + hw:.3f} Y{cy - hd:.3f} E1.0")
            a(f"G1 X{ox + hw:.3f} Y{cy + hd:.3f} E1.0")
            a(f"G1 X{ox - hw:.3f} Y{cy + hd:.3f} E1.0")
            a(f"G1 X{ox - hw:.3f} Y{cy - hd:.3f} E1.0")
            a("G1 X0 Y0 E-.8")  # wipe/retract move: not extrusion
    a("; filament end gcode")
    a("M140 S0")
    a("M104 S0")
    if eject:
        a(f";===== {body_marker} v1 =====")
        a("G1 Z2.5 F600")
        a("G1 Y-0.5 F1500")
        a(f";===== {body_marker} end =====")
    a("M18 X Y Z")
    a("; EXECUTABLE_BLOCK_END")
    a("; filament used [g] = 12.34")
    return "\n".join(out) + "\n"


# ---- inspect_gcode ----------------------------------------------------------------------------------
def test_inspect_header_and_footprint():
    info = inspect_gcode(make_gcode(w=40, d=30, h=10))
    assert info.printer_model == "Bambu Lab A1"
    assert info.print_time_s == 3600 + 600 + 3
    assert info.filament_g == pytest.approx(12.34)
    assert info.filament_types == ["PLA"]
    assert info.nozzle_temps == [220.0]
    assert info.bed_temps == [65.0]
    assert info.max_z == pytest.approx(10.0)
    assert info.layer_count == 50
    assert info.first_layer_bbox == pytest.approx((108.0, 148.0, 113.0, 143.0))
    assert info.footprint_mm == (40.0, 30.0)
    assert info.has_eject_marker is False
    assert info.prime_tower is False
    assert info.warnings == []
    d = info.to_dict()
    assert d["footprint_mm"] == [40.0, 30.0] and d["first_layer_bbox"][0] == 108.0


def test_purge_line_and_wipe_are_not_footprint():
    info = inspect_gcode(make_gcode(w=20, d=20, h=5))
    x0, x1, y0, y1 = info.first_layer_bbox
    assert y0 > 100  # the Y-0.5 purge line before the first marker is ignored
    assert (x0, y0) != (0, 0)  # the negative-E wipe to X0 Y0 is not extrusion


def test_skirt_brim_and_prime_tower_excluded_from_footprint():
    info = inspect_gcode(make_gcode(w=20, d=20, h=5, brim=5, skirt=True, prime_tower=True))
    assert info.footprint_mm == (20.0, 20.0)
    assert info.prime_tower is True
    assert any("prime tower" in w for w in info.warnings)


def test_arc_extremes_are_in_bbox():
    # CCW half circle from (108,113) to (148,113) around (128,113) dips to y = 113 - 20
    ccw = inspect_gcode(make_gcode(w=40, d=30, h=4, arcs="G3"))
    assert ccw.first_layer_bbox[2] == pytest.approx(93.0, abs=0.01)
    cw = inspect_gcode(make_gcode(w=40, d=30, h=4, arcs="G2"))  # passes y = 133, inside the part
    assert cw.first_layer_bbox == pytest.approx((108.0, 148.0, 113.0, 143.0))


def test_eject_marker_body_and_config_only():
    assert inspect_gcode(make_gcode(eject=True)).has_eject_marker is True
    assert inspect_gcode(make_gcode(eject=True, body_marker="HERMES AUTO-EJECT")).has_eject_marker is True
    # a truncated file (tail cut off) still knows from the printer preset's end G-code
    text = make_gcode(eject=True)
    truncated = text[: text.index("; filament end gcode")]
    info = inspect_gcode(truncated)
    assert info.has_eject_marker is True
    # complete file whose preset mentions it but the body lacks it -> warn
    head, body = text.split("; CONFIG_BLOCK_END", 1)
    body = body.replace(";===== HOME3D AUTO-EJECT v1 =====", "").replace(";===== HOME3D AUTO-EJECT end =====", "")
    info = inspect_gcode(head + "; CONFIG_BLOCK_END" + body)
    assert info.has_eject_marker is True
    assert any("not in the executed" in w for w in info.warnings)


def test_marker_in_unrelated_config_key_does_not_count():
    text = make_gcode(extra_config=["; printer_notes = remember HOME3D AUTO-EJECT later"])
    assert inspect_gcode(text).has_eject_marker is False


def test_warnings_model_and_temperatures():
    info = inspect_gcode(make_gcode(model="Bambu Lab A1 mini", nozzle=245, bed=80))
    joined = " | ".join(info.warnings)
    assert "A1 mini" in joined
    assert "nozzle 245" in joined
    assert "bed 80" in joined
    petg = inspect_gcode(make_gcode(material="PETG", nozzle=250, bed=70))
    assert petg.warnings == []
    petg_cold = inspect_gcode(make_gcode(material="PETG", nozzle=210, bed=70))
    assert any("outside the PETG range" in w for w in petg_cold.warnings)


def test_multi_filament_picks_used_slots():
    text = make_gcode()
    text = text.replace("; filament_type = PLA", "; filament_type = PLA;PETG;PLA")
    text = text.replace("; nozzle_temperature = 220", "; nozzle_temperature = 220,250,225")
    text = text.replace("; filament: 1", "; filament: 1,3")
    info = inspect_gcode(text)
    assert info.filament_types == ["PLA"]
    assert info.nozzle_temps == [220.0, 225.0]
    assert info.warnings == []


def test_by_object_first_layer_covers_all_objects():
    info = inspect_gcode(make_gcode(w=20, d=20, h=2, objects=2))
    x0, x1, _, _ = info.first_layer_bbox
    assert x0 == pytest.approx(118.0) and x1 == pytest.approx(178.0)


def test_prusa_style_markers_and_no_header():
    text = make_gcode(w=30, d=30, h=6, header=False, marker=";Z:{z}")
    info = inspect_gcode(text)
    assert info.max_z == pytest.approx(6.0)
    assert info.layer_count == 30
    assert info.footprint_mm == (30.0, 30.0)
    assert info.filament_g == pytest.approx(12.34)  # footer "filament used [g]"


def test_no_markers_falls_back_to_nozzle_z():
    text = make_gcode(w=30, d=20, h=1.0, header=False, marker="; layer")
    info = inspect_gcode(text)
    assert info.footprint_mm == (30.0, 20.0)  # purge at Z0.3 is above the 0.2 first layer
    assert info.max_z == pytest.approx(1.0)


def test_empty_and_garbage_never_raise():
    assert inspect_gcode("").warnings == ["empty G-code"]
    info = inspect_gcode('{"detail":"Not Found"}')
    assert info.first_layer_bbox is None and "no layers found" in info.warnings


def test_simulator_gcode_is_understood():
    sim = pytest.importorskip("home3d_ws.home3d.backends.simulator")
    params = sim._slice_params("box.3mf", (50.0, 40.0, 12.0), eject=True, printer_preset="sim-autoeject")
    info = inspect_gcode(sim.render_gcode(params))
    assert info.has_eject_marker is True
    assert info.printer_model == "Bambu Lab A1"
    assert info.footprint_mm == pytest.approx((50.0, 40.0), abs=0.01)
    assert info.max_z == pytest.approx(12.0, abs=0.2)
    assert info.filament_types == ["PLA"] and info.print_time_s and info.filament_g
    assert info.warnings == []
    assert assess_eject(info).eligible


# ---- footprint_at -----------------------------------------------------------------------------------
def test_footprint_at_layers():
    text = make_gcode(w=40, d=40, h=10, top_scale=0.25)
    base = footprint_at(text, 0.2)
    mid = footprint_at(text, 5.0)
    top = footprint_at(text, 10.0)
    assert base == pytest.approx((108.0, 148.0, 108.0, 148.0))
    assert (mid[1] - mid[0]) < 40 and (top[1] - top[0]) == pytest.approx(10.0, abs=0.01)
    assert footprint_at(text, 0.0) == base  # below the first layer -> first layer
    assert footprint_at(text, 0.95) == footprint_at(text, 1.0)  # height inside a layer -> that layer
    assert footprint_at(text, 25.0) is None  # above the part


# ---- assess_eject -----------------------------------------------------------------------------------
def _info(w=40.0, d=40.0, h=10.0, types=("PLA",)) -> GcodeInfo:
    return GcodeInfo(printer_model="Bambu Lab A1", max_z=h, layer_count=int(h / 0.2),
                     first_layer_bbox=(100.0, 100.0 + w, 100.0, 100.0 + d), filament_types=list(types))


def test_sturdy_pla_accepted():
    a = assess_eject(_info(60, 40, 12))
    assert a.eligible is True
    assert a.push_z == gcode.PRESET_PUSH_Z_MM
    assert any("check shape" in r for r in a.reasons)


def test_tall_narrow_refused():
    a = assess_eject(_info(20, 16, 50))
    assert a.eligible is False and a.push_z is None
    assert any("tall and narrow" in r for r in a.reasons)


def test_petg_and_tpu_refused():
    a = assess_eject(_info(types=("PETG",)), material="PETG")
    assert not a.eligible and any("PETG" in r for r in a.reasons)
    # the G-code wins over a wrong material argument
    assert not assess_eject(_info(types=("PETG HF",)), material="PLA").eligible
    t = assess_eject(_info(types=("TPU 95A",)), material="TPU")
    assert not t.eligible and any("flexible" in r for r in t.reasons)
    assert not assess_eject(_info(types=("ABS",)), material="ABS").eligible


def test_pla_like_materials_accepted():
    for m in ("PLA Matte", "PLA+", "PHA", "PLA-CF"):
        assert assess_eject(_info(types=(m,)), material=m).eligible, m


def test_thin_part_refused_unless_large_and_above_push():
    thin = assess_eject(_info(50, 50, 2.0))
    assert not thin.eligible and any("passes over" in r for r in thin.reasons)
    # 2.8 mm but wide and flat: the push at Z2.5 still catches it
    assert assess_eject(_info(80, 70, 2.8)).eligible
    # 2.8 mm on a normal footprint: refused (under 3 mm)
    assert not assess_eject(_info(40, 40, 2.8)).eligible
    # thinner than the push height is refused even when large
    assert not assess_eject(_info(120, 120, 2.4)).eligible


def test_tiny_footprint_refused():
    a = assess_eject(_info(12, 30, 5))
    assert not a.eligible and any("rolls" in r for r in a.reasons)


def test_unknown_geometry_refused():
    a = assess_eject(GcodeInfo())
    assert not a.eligible
    assert any("height unknown" in r for r in a.reasons) and any("footprint unknown" in r for r in a.reasons)


def test_thresholds_are_parameters():
    info = _info(20, 20, 45)  # aspect 2.25
    assert assess_eject(info).eligible
    assert not assess_eject(info, max_aspect=2.0).eligible
    assert not assess_eject(_info(20, 20, 5), min_footprint_mm=25).eligible


def test_material_family():
    fam = gcode.material_family
    assert fam("PLA Basic") == "PLA" and fam("pctg") == "PETG" and fam("TPU 95A") == "TPU"
    assert fam("ASA") == "ASA" and fam("PC") == "PC" and fam("") == ""
